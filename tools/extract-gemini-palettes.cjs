const KEYS = ["type", "Background", "Foreground", "LightBlue", "AccentBlue", "AccentPurple", "AccentCyan", "AccentGreen", "AccentYellow", "AccentRed", "DiffAdded", "DiffRemoved", "Comment", "Gray", "DarkGray", "InputBackground", "MessageBackground", "FocusBackground", "GradientColors"];
const out = {};
for (const [id, f] of Object.entries(files)) {
  const t = fs.readFileSync(BASE + f, "utf8");
  const m = t.match(/const \w+Colors: ColorsTheme = \{([\s\S]*?)\n\};/);
  if (!m) { console.error("MISS", f); continue; }
  const o = {};
  for (const line of m[1].split("\n")) {
    const kv = line.trim().match(/^(\w+):\s*('[^']*'|\[[^\]]*\]),?$/);
    if (!kv) continue;
    let v = kv[2];
    if (v.startsWith("[")) {
      if (!v.includes("'")) continue; // identifier-referenced gradient: skip, derivation has a fallback
      v = "[" + v.slice(1, -1).replace(/'/g, '"') + "]";
    } else {
      v = '"' + v.slice(1, -1) + '"';
    }
    o[kv[1]] = JSON.parse(v);
  }
  out[id] = o;
}
